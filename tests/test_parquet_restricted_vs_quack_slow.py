@pytest.mark.parametrize('case', sorted(CASES))
def test_the_port_reproduces_quack(case):
    """Every long case against the Fortran's numbers at the bars of its path."""
    result = run_case(case, CASES)
    kind, _, _, bar_class = CASES[case]
    quack = QUACK[case]
    if bar_class == 'chaotic':
        if 'eqp_first_iteration' in quack:
            assert_first_iteration(result, case, quack, EXACT_EQP)
        assert_matches_quack(result, case, quack, CHAOTIC_EQP, None, CHAOTIC_COUNT_SLACK,
                             change_rel=CHAOTIC_CHANGE_REL)
    else:
        assert_matches_quack(result, case, quack, EXACT_EQP, EXACT_Z_REL, 0)
    assert result.converged_1b is QUACK_ONE_BODY_CONVERGED.get(case), case
    if result.options['tda_eh'] and result.options['tda_pp']:
        assert_tda_energies(result, case)


def test_every_case_has_its_quack_numbers():
    """No case runs without a reference, and none is recorded without a run."""
    assert set(CASES) == set(QUACK) == set(SOURCES)


def run():
    """Every case as a script; True when all passed."""
    ok = True
    for case in sorted(CASES):
        try:
            test_the_port_reproduces_quack(case)
            print(f'  [ok] {case}')
        except AssertionError as err:
            ok = False
            print(f'  [FAIL] {case}: {err}')
    print('\nALL PASSED' if ok else '\nFAILURES DETECTED')
    return ok


if __name__ == '__main__':
    sys.exit(0 if run() else 1)
