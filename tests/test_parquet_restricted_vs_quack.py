@functools.lru_cache(maxsize=None)
def rhf(molecule):
    """The RHF of `molecule` (GEOMETRIES) the Fortran runs started from."""
    mol = gto.M(atom=GEOMETRIES[molecule], basis=BASIS, verbose=0)
    mf = scf.RHF(mol)
    mf.conv_tol = SCF_CONV_TOL
    mf.kernel()
    assert mf.converged, molecule
    return mf


@functools.lru_cache(maxsize=None)
def mo_integrals(molecule):
    """(eps, eri, nO): the RHF energies, <pq|rs> and the doubly occupied
    orbitals, as the Fortran's R_evParquet got them."""
    mf = rhf(molecule)
    n = mf.mo_coeff.shape[1]
    chem = ao2mo.full(mf.mol, mf.mo_coeff, compact=False).reshape((n,) * 4)
    eri = np.ascontiguousarray(chem.transpose(0, 2, 1, 3))
    eri.setflags(write=False)
    return np.asarray(mf.mo_energy), eri, mf.mol.nelectron // 2


def qs_inputs(molecule, orthogonalizer='evd'):
    """The AO arrays the Fortran's R_qsParquet got (qs_parquet's arguments):
    Hc = T + V, <mu nu|la si>, P = 2 C_occ C_occ^T and the canonical
    orthogonalizer of S by numpy's eigh ('evd', which the Fortran runs of
    the 'qs' cases were given) or by dsyev ('dsyev',
    `restricted.orthogonalization_matrix`, as Quack's own
    utils/orthogonalization_matrix, which those of the 'qs_dsyev' cases
    took)."""
    mf = rhf(molecule)
    mol = mf.mol
    s = mol.intor('int1e_ovlp')
    if orthogonalizer == 'evd':
        u, vecs = np.linalg.eigh(s)
        keep = u > ORTHOGONALIZER_CUT
        x = vecs[:, keep] / np.sqrt(u[keep])
    else:
        x = restricted.orthogonalization_matrix(s)
    c = np.asarray(mf.mo_coeff)
    nO = mol.nelectron // 2
    return dict(eps_hf=np.asarray(mf.mo_energy), c_hf=c, s=s, x=x,
                hc=mol.intor('int1e_kin') + mol.intor('int1e_nuc'),
                eri_ao=np.ascontiguousarray(mol.intor('int2e').transpose(0, 2, 1, 3)), nO=nO,
                p_hf=2.0 * c[:, :nO] @ c[:, :nO].T)


def run_case(case, cases=None):
    """The port's result of `case` (CASES, or the `cases` handed in): kind
    'ev' and 'ev_first' ev_parquet on the MO integrals, 'qs' and 'qs_dsyev'
    qs_parquet on the AO arrays (`qs_inputs`), 'qs_front' run_parquet."""
    kind, scheme, options, _ = (CASES if cases is None else cases)[case]
    molecule = case.split('/')[0]
    with warnings.catch_warnings():
        warnings.simplefilter('ignore')
        if kind in ('ev', 'ev_first'):
            eps, eri, nO = mo_integrals(molecule)
            return restricted.ev_parquet(eps, eri, nO, scheme, **options)
        if kind in ('qs', 'qs_dsyev'):
            x = 'dsyev' if kind == 'qs_dsyev' else 'evd'
            return restricted.qs_parquet(**qs_inputs(molecule, x), **options)
        return restricted.run_parquet(rhf(molecule), 'qs', **options)


def bars(kind):
    """(eqp in Ha, Z relative, count slack) of a bar class of CASES."""
    if kind == 'diis':
        return DIIS_EQP, DIIS_Z_REL, DIIS_COUNT_SLACK
    return EXACT_EQP, EXACT_Z_REL, 0


def assert_within(got, want, bar, label, relative=False):
    """Raise unless every element of `got` is within `bar` of `want`
    (relative to |want| when `relative`), saying how far it was."""
    got, want = np.asarray(got, dtype=float), np.asarray(want, dtype=float)
    assert got.shape == want.shape, (label, got.shape, want.shape)
    gap = np.abs(got - want)
    if relative:
        gap = gap / np.abs(want)
    assert np.all(gap <= bar), (label, f'max gap {gap.max():.3e} against {bar:.0e}',
                                int(np.argmax(gap)))


def newton_held(result, z_quack):
    """The orbitals (0-based) whose root and Z are held against Quack's: all
    of them unless the run solved the quasiparticle equation by Quack's
    Newton, and then those whose Z in Quack's record (`z_quack`, the
    iteration held) is at least Z_HELD."""
    z_quack = np.asarray(z_quack, dtype=float)
    if result.options.get('qp_solver') != NEWTON_LABEL:
        return np.arange(len(z_quack))
    return np.flatnonzero(z_quack >= Z_HELD)


def assert_first_iteration(result, case, quack, bar):
    """The first one-body iteration's eqp against Quack's, on the orbitals
    `newton_held` reads off Quack's first-iteration Z (all of them where no
    Z of it is recorded, a run without Newton), and its two-body count
    exactly."""
    first = np.asarray(result.history[0]['eqp'])
    held = (newton_held(result, quack['z_first_iteration']) if 'z_first_iteration' in quack
            else np.arange(len(first)))
    assert_within(first[held], np.asarray(quack['eqp_first_iteration'])[held], bar,
                  (case, 'first-iteration eqp'))
    assert result.n_it_2b[0] == quack['n_it_2b'][0], (case, result.n_it_2b)


def assert_matches_quack(result, case, quack, eqp_bar, z_bar, count_slack, change_rel=0.0):
    """Hold the port's `result` of `case` to Quack's numbers `quack` (one
    QUACK entry): the last iteration's eqp, SigC, eQPlin and the one-body
    changes within eqp_bar (Ha; a change also within change_rel of Quack's,
    where that is larger), Z within z_bar relative (None: not held), the
    two-body counts within count_slack, the EcRPA parts within EC_ABS. A run
    by Quack's Newton has its eqp and Z held on the orbitals of
    `newton_held` only, and its one-body change where Quack's largest change
    lies on one of them (an osPA's or FLEX's single change is
    max |eQP - eHF|); SigC and eQPlin, taken before the search, on all."""
    assert result.n_it_1b == quack['n_it_1b'], (case, result.n_it_1b)
    counts = np.array(result.n_it_2b) - np.array(quack['n_it_2b'])
    assert np.all(np.abs(counts) <= count_slack), (case, result.n_it_2b, quack['n_it_2b'])
    held = newton_held(result, quack['z']) if 'z' in quack else np.arange(len(result.eqp))
    assert_within(result.eqp[held], np.asarray(quack['eqp'])[held], eqp_bar, (case, 'eqp'))
    sigc = result.sigc if result.sigc.ndim == 1 else np.diag(result.sigc)
    assert_within(sigc, quack['sigc'], eqp_bar, (case, 'sigc'))
    changes = np.array([h['err_1b'] for h in result.history])
    quack_changes = np.asarray(quack['err_1b'], dtype=float)
    if len(held) < len(result.eqp):
        assert quack['n_it_1b'] == 1, (case, 'an evPA by Newton with orbitals not held')
        if np.argmax(np.abs(np.asarray(quack['eqp']) - result.eps_hf)) not in held:
            changes = quack_changes = np.zeros(0)
    assert changes.shape == quack_changes.shape, (case, 'err_1b', changes.shape)
    gap = np.abs(changes - quack_changes)
    bar = np.maximum(eqp_bar, change_rel * np.abs(quack_changes))
    assert np.all(gap <= bar), (case, 'err_1b', gap.tolist(), bar.tolist())
    if 'z' in quack and z_bar is not None:
        assert_within(result.z[held], np.asarray(quack['z'])[held], z_bar, (case, 'z'),
                      relative=True)
    if 'eqp_lin' in quack:
        assert_within(result.eqp_lin, quack['eqp_lin'], eqp_bar, (case, 'eqp_lin'))
    for key in ('ec_eh_spin', 'ec_pp_spin'):
        if key in quack:
            assert_within(getattr(result, key), quack[key], EC_ABS, (case, key))


def assert_tda_energies(result, case):
    """Under TDA Quack's EcRPA is rounding noise, and the channel energy is
    singlet + 3 triplet to the bit."""
    assert abs(result.ec_eh) < TDA_EC_NOISE and abs(result.ec_pp) < TDA_EC_NOISE, case
    singlet, triplet = result.ec_eh_spin
    assert result.ec_eh == singlet + 3.0 * triplet, case
    singlet, triplet = result.ec_pp_spin
    assert result.ec_pp == singlet + 3.0 * triplet, case


@pytest.mark.parametrize('case', sorted(CASES))
def test_the_port_reproduces_quack(case):
    """eqp, SigC, Z, eQPlin, the one-body changes and the two-body counts of
    every case against the Fortran's, at the bars of its path."""
    result = run_case(case)
    kind, scheme, _, bar_class = CASES[case]
    if kind == 'ev_first':
        assert_first_iteration(result, case, QUACK[case], EXACT_EQP)
    else:
        assert_matches_quack(result, case, QUACK[case], *bars(bar_class))
    if case in QUACK_ONE_BODY_CONVERGED:
        assert result.converged_1b is QUACK_ONE_BODY_CONVERGED[case], case
    elif kind == 'ev':
        assert result.converged_1b is None, case       # FLEX and osPA: no one-body loop
    if result.options['tda_eh'] and result.options['tda_pp']:
        assert_tda_energies(result, case)


def test_every_case_has_its_quack_numbers():
    """No case runs without a reference, and none is recorded without a run."""
    assert set(CASES) == set(QUACK) == set(SOURCES)


def run():
    """Every case as a script; True when all passed."""
    ok = True
    for case in sorted(CASES):
        try:
            test_the_port_reproduces_quack(case)
            print(f'  [ok] {case}')
        except AssertionError as err:
            ok = False
            print(f'  [FAIL] {case}: {err}')
    print('\nALL PASSED' if ok else '\nFAILURES DETECTED')
    return ok


if __name__ == '__main__':
    sys.exit(0 if run() else 1)
