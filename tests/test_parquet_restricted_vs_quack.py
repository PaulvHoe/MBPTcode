"""The closed-shell parquet driver against Quack's Fortran: the short runs.

`restricted.ev_parquet` (FLEX, osPA, evPA), `restricted.qs_parquet` (qsPA)
and the front door `run_parquet` on water and ammonia 6-31G, held against
the paper-era Quack (git e3528a40): R_evParquet, and R_qsParquet with the
omega = 0d0 that its four R_*_Phi calls miss (the paper tree's call has
undefined behaviour). The Fortran does not run here, so its numbers are
recorded in QUACK, each case with the Fortran run it comes from (SOURCES);
`test_parquet_restricted_vs_quack_slow` holds the long runs on the same
inputs and helpers.

The inputs are those the Fortran runs were given: an RHF converged to
conv_tol 1e-12 on the geometries of QuAcK's mol/ files, eri = <pq|rs> from
ao2mo.full. qsPA takes the AO overlap, Hc = T + V, <mu nu|la si>,
P = 2 C_occ C_occ^T and the orthogonalizer the Fortran run had: numpy's
eigh of S (`qs_inputs` 'evd'), or for the front door its own dsyev one against
Quack's own (run_parquet).

How tightly (the bars below, each with what was measured: every case at 1
to 4 threads, and at 2 threads after 24 one-ulp changes of the core
Hamiltonian, the last bits another BLAS gives an SCF): on a path without
two-body DIIS port and Quack agree to 4.7e-12 Ha and 1.6e-10 relative in Z,
so eqp, SigC and the one-body changes are held to EXACT_EQP and Z to
EXACT_Z_REL, the counts exactly (their smallest margin to the threshold is
1.6e-4 relative). Two-body DIIS solves systems below rcond = eps (cond 1e14
to 1e18), whose weights rounding sets (`test_parquet_diis` holds them
against Quack's); its paths agree far better than cond x eps would say,
to 1.3e-12 Ha with the same counts, but a count may move on another BLAS
and the loop then stop at another iterate: DIIS_EQP, DIIS_Z_REL and counts
within DIIS_COUNT_SLACK (qsPA with two-body DIIS among them, whose history
R_qsParquet empties at every one-body iteration: carried over, the second
and third loops take 63 and 91 iterations against Quack's 56 and 57).
Quack's Newton is chaotic beside a pole of the weakly regularized
self-energy (s_1b = 1e8): the root and Z it
keeps for an orbital whose Z lies below Z_HELD move with the last bits of
its start, in Quack and in the port, so in every case it solves those
orbitals' eqp and Z are not held (`newton_held`, which reads Quack's Z; it
also leaves out three stable orbitals of each FLEX RPA case), and the evPA
at s_1b = 1e8 is held at its first one-body iteration. The paper's numbers
are aug-cc-pVTZ, which no short run reaches, so none is held here.

Run: python tests/test_parquet_restricted_vs_quack.py, or under pytest.
"""
