@functools.lru_cache(maxsize=None)
def mean_field(molecule):
    """The RHF (water, ammonia) or UHF (oh) the Fortran runs started from."""
    atom, charge, spin = MOLECULES[molecule]
    mol = gto.M(atom=atom, basis=BASIS, charge=charge, spin=spin, verbose=0)
    mf = scf.RHF(mol) if spin == 0 else scf.UHF(mol)
    mf.conv_tol = SCF_CONV_TOL
    mf.kernel()
    assert mf.converged, molecule
    return mf


def pinned_uhf(mol, hcore=None):
    """The UHF of the linear open shell `mol` (core Hamiltonian `hcore`,
    default its own) whose singly occupied pi hole lies on the x axis:
    converged to SCF_CONV_TOL from the density of the UHF in a field of
    PIN_FIELD au along x.

    From the default guess, roundoff picks the direction of the hole about
    the bond: OH's lies 132 degrees off x here and anywhere from -36 to 106
    degrees after a one-ulp change of Hc. The MO-basis quantities (eqp, SigC,
    Z, the two-body counts) do not depend on it; qsPA's err_1b, Quack's
    max |F P S - S P F| over AO elements, does (by 2e-5 to 1.5e-4 Ha). Pinned,
    the hole lies at 0 degrees to roundoff, and port and Quack's err_1b agree
    to 1.7e-14 Ha at 1 to 4 threads and after 24 one-ulp changes of Hc."""
    mf = scf.UHF(mol)
    if hcore is not None:
        mf.get_hcore = lambda *args, h=hcore: h
    with mol.with_common_orig((0.0, 0.0, 0.0)):
        field = PIN_FIELD * mol.intor_symmetric('int1e_r')[0]
    biased = scf.UHF(mol)
    biased.get_hcore = lambda *args, h=mf.get_hcore() + field: h
    biased.conv_tol = PIN_CONV_TOL
    biased.kernel()
    assert biased.converged
    mf.conv_tol = SCF_CONV_TOL
    mf.kernel(dm0=biased.make_rdm1())
    assert mf.converged
    return mf


@functools.lru_cache(maxsize=None)
def pinned_mean_field(molecule):
    """The UHF of an open shell (oh) its qsPA cases start from (`pinned_uhf`)."""
    atom, charge, spin = MOLECULES[molecule]
    return pinned_uhf(gto.M(atom=atom, basis=BASIS, charge=charge, spin=spin, verbose=0))


@functools.lru_cache(maxsize=None)
def closed_shell_spin_orbitals(molecule):
    """(eps, eri, nO) of a closed shell over interleaved spin orbitals, as the
    Fortran's G_evParquet got them: eps repeated, <PQ|RS> = <pq|rs> where the
    spins of P and R agree and those of Q and S do, else 0."""
    mf = mean_field(molecule)
    n = mf.mo_coeff.shape[1]
    eri = ao2mo.full(mf.mol, mf.mo_coeff, compact=False).reshape((n,) * 4).transpose(0, 2, 1, 3)
    spin = np.tile([0, 1], n)
    orbital = np.repeat(np.arange(n), 2)
    same = spin[:, None] == spin[None, :]
    both_spins_kept = same[:, None, :, None] & same[None, :, None, :]
    eri_so = eri[np.ix_(orbital, orbital, orbital, orbital)] * both_spins_kept
    eri_so = np.ascontiguousarray(eri_so)
    eri_so.setflags(write=False)
    return np.repeat(np.asarray(mf.mo_energy), 2), eri_so, 2 * (mf.mol.nelectron // 2)


@functools.lru_cache(maxsize=None)
def open_shell_spin_orbitals(molecule):
    """(eps, eri, nO) of a UHF in the driver's layout (`spin_orbital_reference`,
    `spin_orbital_eri`), as the Fortran got them."""
    ref = spin_orbital.spin_orbital_reference(mean_field(molecule))
    eri = spin_orbital.spin_orbital_eri(ref.eri_ao, ref.mo_coeff)
    eri.setflags(write=False)
    return ref.eps, eri, ref.nO


def run_case(case, cases=None):
    """The port's result of `case` (CASES, or the `cases` handed in)."""
    scheme, options, _ = (CASES if cases is None else cases)[case]
    molecule = case.split('/')[0]
    with warnings.catch_warnings():
        warnings.simplefilter('ignore')
        if scheme == 'qs':
            mf = (mean_field(molecule) if MOLECULES[molecule][2] == 0
                  else pinned_mean_field(molecule))
            ref = spin_orbital.spin_orbital_reference(mf)
            x = spin_orbital.orthogonalization_matrix(ref.ovlp)
            return spin_orbital.qs_parquet_so(ref.eps, ref.mo_coeff, ref.ovlp, x, ref.hcore,
                                              ref.eri_ao, ref.nO, **options)
        if MOLECULES[molecule][2] == 0:
            eps, eri, nO = closed_shell_spin_orbitals(molecule)
        else:
            eps, eri, nO = open_shell_spin_orbitals(molecule)
        return spin_orbital.ev_parquet_so(eps, eri, nO, scheme, **options)


def assert_within(got, want, bar, label, relative=False):
    """Raise unless every element of `got` is within `bar` of `want`
    (relative to |want| when `relative`), saying how far it was."""
    got, want = np.asarray(got, dtype=float), np.asarray(want, dtype=float)
    assert got.shape == want.shape, (label, got.shape, want.shape)
    gap = np.abs(got - want)
    if relative:
        gap = gap / np.abs(want)
    assert np.all(gap <= bar), (label, f'max gap {gap.max():.3e} against {bar:.0e}',
                                int(np.argmax(gap)))


def assert_matches_quack(result, case, quack, bar_class):
    """Hold the port's `result` of `case` to Quack's numbers `quack` (one
    QUACK entry) at the bars of `bar_class`."""
    assert result.n_it_1b == quack['n_it_1b'], (case, result.n_it_1b)
    if bar_class == 'cut':
        eqp_bar, z_bar = CUT_EQP, CUT_Z_REL
        assert result.n_it_2b[0] == quack['n_it_2b'][0], (case, result.n_it_2b)
        assert_within(result.history[0]['eqp'], quack['eqp_first_iteration'], EXACT_EQP,
                      (case, 'first-iteration eqp'))
        assert_within(result.history[0]['err_1b'], quack['err_1b'][0], EXACT_EQP,
                      (case, 'first err_1b'))
        assert_within([h['err_1b'] for h in result.history], quack['err_1b'], CUT_EQP,
                      (case, 'err_1b'))
    else:
        eqp_bar = QS_DIIS_EQP if bar_class == 'qs_diis' else EXACT_EQP
        z_bar = EXACT_Z_REL
        assert result.n_it_2b == quack['n_it_2b'], (case, result.n_it_2b)
        assert_within([h['err_1b'] for h in result.history], quack['err_1b'], EXACT_EQP,
                      (case, 'err_1b'))
    assert_within(result.eqp, quack['eqp'], eqp_bar, (case, 'eqp'))
    if 'sigc' in quack:
        sigc = result.sigc if result.sigc.ndim == 1 else np.diag(result.sigc)
        assert_within(sigc, quack['sigc'], eqp_bar, (case, 'sigc'))
    if 'z' in quack:
        assert_within(result.z, quack['z'], z_bar, (case, 'z'), relative=True)
    if 'eqp_lin' in quack:
        assert_within(result.eqp_lin, quack['eqp_lin'], eqp_bar, (case, 'eqp_lin'))
    for key in ('ec_eh', 'ec_pp'):
        if key in quack:
            assert_within(getattr(result, key), quack[key], EC_ABS, (case, key))


def assert_verdicts(result, case, scheme, quack_converged=None):
    """FLEX and osPA have no one-body verdict; evPA and qsPA have Quack's
    (`quack_converged`, False where it ran max_it_1b iterations). Under TDA
    the EcRPA is rounding noise."""
    if scheme == 'os':
        assert result.converged_1b is None, case
    else:
        assert result.converged_1b is quack_converged, (case, result.converged_1b)
    if result.options['tda_eh']:
        assert abs(result.ec_eh) < TDA_EC_NOISE, (case, result.ec_eh)
    if result.options['tda_pp']:
        assert abs(result.ec_pp) < TDA_EC_NOISE, (case, result.ec_pp)


#: Quack's verdict on the evPA and qsPA one-body loops of CASES.
QUACK_ONE_BODY_CONVERGED = dict.fromkeys(
    [case for case, (scheme, _, _) in CASES.items() if scheme != 'os'], False)


@pytest.mark.parametrize('case', sorted(CASES))
def test_the_port_reproduces_quack(case):
    """eqp, SigC, Z, eQPlin, the one-body changes and the two-body counts of
    every case against the Fortran's, at the bars of its path."""
    result = run_case(case)
    scheme, _, bar_class = CASES[case]
    assert_matches_quack(result, case, QUACK[case], bar_class)
    assert_verdicts(result, case, scheme, QUACK_ONE_BODY_CONVERGED.get(case))


def test_every_case_has_its_quack_numbers():
    """No case runs without a reference, and none is recorded without a run."""
    assert set(CASES) == set(QUACK) == set(SOURCES)


def test_qspa_two_body_diis_starts_afresh_at_each_one_body_iteration():
    """G_qsParquet empties its two-body DIIS history at every one-body
    iteration: the first two iterations of the slow file's water qsPA with
    one-body and two-body DIIS 5 (s_1b = 50) take Quack's two-body counts
    and one-body changes (a history carried over takes 88 two-body
    iterations at the second, against Quack's 72). The first iterations do
    not depend on the cap."""
    from tests.test_parquet_so_vs_quack_slow import CASES as SLOW_CASES
    from tests.test_parquet_so_vs_quack_slow import QUACK as SLOW_QUACK
    case = 'water/qs_tda_s2b1_s1b50_d5'
    scheme, options, bar_class = SLOW_CASES[case]
    result = run_case(case, {case: (scheme, dict(options, max_it_1b=2), bar_class)})
    quack = SLOW_QUACK[case]
    assert result.n_it_2b == quack['n_it_2b'][:2], (result.n_it_2b, quack['n_it_2b'][:2])
    assert_within([h['err_1b'] for h in result.history], quack['err_1b'][:2], EXACT_EQP,
                  (case, 'err_1b'))


